// The inspection is the original's, plus one provenance line from the design.
// ---------------------------------------------------------------------------

const ORIGINALS: Record<string, EvidenceDef[]> = { S001C01: c01, S001C02: c02, S001C03: c03, S001C04: c04, S001C05: c05 };

/** Source ids the build could not find, listed by the check rather than invented. */
export const MISSING_SOURCES: string[] = [];

const recovered = (id: string, canonical: string, sourceLocationId: string, holder: string, provenance: string): EvidenceDef[] => {
  const m = /^S(\d{3})-C(\d{2})-(E\d{3})$/.exec(canonical)!;
  const original = ORIGINALS[`S${m[1]}C${m[2]}`]?.find((e) => e.id === m[3]);
  if (!original) {
    MISSING_SOURCES.push(`${id} (${canonical})`);
    return [];
  }
  return [
    {
      ...original,
      id,
      canonical,
      sourceLocationId,
      inspection: original.inspection + "\n\n" + provenance,
      image: `ev.${id}`,
      // The original's cross-references point at the earlier case's numbering; here they would point at the wrong items.
      related: [],
      discovery: `A recovery route (bible section 7): ${holder} hands it over from chapter 2 on, asked about it, unless the original is already held on the rolling board.`,
      ...(original.readAloud ? { readAloud: [...original.readAloud, { text: provenance }] } : {}),
    },
  ];
};

